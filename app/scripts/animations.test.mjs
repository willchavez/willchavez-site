import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { promisify } from 'node:util';
import { execFile } from 'node:child_process';
import sharp from 'sharp';
import { buildAnimations } from './animations.mjs';
const exec = promisify(execFile);

test('animation videos preserve timing and frames, reuse cache, and invalidate changed sources', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'animation-viewer-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const directory = path.join(root, 'public/img/portfolio');
  await fs.mkdir(directory, { recursive: true });
  const source = path.join(directory, 'demo.gif');
  const create = async (delay) => {
    const pixels = Buffer.from([...Array(12).fill([255, 0, 0]).flat(), ...Array(12).fill([0, 0, 255]).flat()]);
    await sharp(pixels, { raw: { width: 4, height: 6, channels: 3, pageHeight: 3 } }).gif({ delay, loop: 0 }).toFile(source);
  };
  await create([100, 300]);
  await sharp({ create: { width: 4, height: 4, channels: 3, background: 'red' } }).png().toFile(path.join(directory, 'still.png'));
  const first = await buildAnimations(root);
  const url = first['/img/portfolio/demo.gif'];
  assert(url);
  assert.equal(first['/portfolio-media/w/1600/demo.webp'], url);
  assert.equal(first['/img/portfolio/still.png'], undefined);
  const video = path.join(root, 'dist', url);
  const { stdout } = await exec('ffprobe', ['-v', 'error', '-show_entries', 'format=duration:stream=codec_name,width,height', '-of', 'json', video]);
  const probe = JSON.parse(stdout);
  assert.equal(probe.streams[0].codec_name, 'h264');
  assert.equal(probe.streams[0].height, 4, 'odd dimensions are padded for browser decoding');
  assert(Math.abs(Number(probe.format.duration) - 0.4) < 0.1, 'preserves variable frame duration');
  const { stdout: frames } = await exec('ffmpeg', ['-v', 'error', '-i', video, '-f', 'framemd5', '-']);
  assert(new Set(frames.split('\n').filter(line => line && !line.startsWith('#')).map(line => line.split(',').at(-1).trim())).size > 1);
  const cached = await fs.readFile(video);
  await fs.rm(path.join(root, 'dist'), { recursive: true });
  assert.deepEqual(await buildAnimations(root), first);
  assert.deepEqual(await fs.readFile(video), cached);
  await create([10, 70]);
  const changedUrl = (await buildAnimations(root))['/img/portfolio/demo.gif'];
  assert.notEqual(changedUrl, url);
  const { stdout: fast } = await exec('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'json', path.join(root, 'dist', changedUrl)]);
  assert(Math.abs(Number(JSON.parse(fast).format.duration) - .08) < .015, 'short GIF frames retain millisecond timing');
  await fs.unlink(source);
  await fs.rm(path.join(root, 'dist'), { recursive: true });
  assert.deepEqual(await buildAnimations(root), {});
});
